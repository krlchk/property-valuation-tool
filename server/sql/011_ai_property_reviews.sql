-- Stores the values produced while generating a property's AI-assisted offer.
-- estimated_price is the condition-adjusted value returned by the estimate flow.
-- final_estimated_price is the value after applying the selected offer-term
-- multiplier and is the value presented as the final offer estimate.

create table if not exists public.ai_property_reviews (
  id bigint generated by default as identity primary key,
  property_id uuid not null references public.properties(id) on delete cascade,

  estimated_price numeric(12, 2) not null,
  condition_adjustment_pct numeric(7, 2) not null,
  offer_term_pct numeric(7, 2) not null,
  final_estimated_price numeric(12, 2) not null,

  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists idx_ai_property_reviews_property_id
  on public.ai_property_reviews(property_id);

alter table public.ai_property_reviews enable row level security;
